/* ── Chart series helpers ─────────────────────────────────────────────────── */

export function mockSeries(seed: number, points = 12, base = 100, volatility = 0.08) {
  let value = base;
  return Array.from({ length: points }, (_, i) => {
    value = value * (1 + (Math.sin((i + seed) / 2.2) * volatility) + (Math.random() - 0.5) * volatility * 0.6);
    return value;
  });
}

export function mockTimeSeries(seed: number, points = 12, base = 100, volatility = 0.08) {
  const values = mockSeries(seed, points, base, volatility);
  // Labels derive from MOCK_REFERENCE (not Date.now()) so server-rendered and
  // client-rendered output always match — demo data never depends on the clock.
  return values.map((v, i) => ({
    label: new Intl.DateTimeFormat("en-US", { month: "short" }).format(
      new Date(MOCK_REFERENCE - (points - i) * 30 * 86400000)
    ),
    value: Math.round(v * 100) / 100,
  }));
}
